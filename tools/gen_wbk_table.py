#!/usr/bin/env python3
"""Build src/wbk-table.js from LibRaw's adobe_coeff table (colordata.cpp, LGPL/CDDL, see THIRD_PARTY_NOTICES.md).

Each row: [make, model prefix, the 3x3 XYZ->camera matrix x10000]. Order kept, because LibRaw takes the first
prefix that matches and lists longer names first ("EOS 6D Mark II" before "EOS 6D")."""
import re, json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'libraw-wasm-gpl3/vendor/LibRaw/src/tables/colordata.cpp').read_text(errors='replace')
body = src[src.index('table[] = {'):src.index('};', src.index('table[] = {'))]
body = re.sub(r'#ifdef USE_6BY9RPI.*?#endif', '', body, flags=re.S)
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)   # comments can hold quoted names ("X-T1IR")
body = re.sub(r'//[^\n]*', '', body)
rows = []
for m in re.finditer(r'\{\s*LIBRAW_CAMERAMAKER_(\w+),\s*"([^"]*)",\s*(-?(?:0x)?[0-9a-fA-F]+),\s*(-?(?:0x)?[0-9a-fA-F]+),\s*\{([^}]*)\}', body):
    nums = [int(x) for x in re.findall(r'-?\d+', m.group(5))]
    if len(nums) < 9 or not any(nums[:9]): continue
    rows.append([m.group(1), m.group(2), nums[:9]])
out = ('/* Generated by tools/gen_wbk_table.py from LibRaw colordata.cpp (adobe_coeff): camera make, model prefix,\n'
       '   XYZ->camera matrix x10000. Used only to put the white balance in Kelvin (src/wb-kelvin.js). */\n'
       'const WBK_TABLE = ' + json.dumps(rows, separators=(',', ':')) + ';\n')
(root / 'src/wbk-table.js').write_text(out)
print(len(rows), 'cameras,', len(out), 'bytes')
