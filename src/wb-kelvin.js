/* Build 194: Temperature in Kelvin for RAW files.

   The slider itself is unchanged -- the same position, the same warm/cool gains, so saved edits, looks and links mean
   what they did. What changes is the number on it. For a RAW file we know enough to say which light the picture is
   balanced for: the white balance the decode applied (res.__wb), the camera's colour matrix, and the slider's own
   gains on top. A light the camera would record as (1/wb) after the slider's gains are undone is the light that comes
   out neutral, and its colour gives a correlated colour temperature, the same quantity Lightroom shows.

   The camera's XYZ->camera matrix comes from LibRaw's own table (src/wbk-table.js, generated by
   tools/gen_wbk_table.py). The decoder reports rgb_cam, not the table row it used, so the row is found by rebuilding
   rgb_cam from each candidate the way LibRaw does (cam_xyz_coeff) and keeping the one that reproduces it. That needs
   no model name, survives regional names (Rebel T5 vs 1200D), and when the matrix came from somewhere else -- a DNG's
   own tags, a maker note -- nothing matches and the slider simply keeps its +/- numbers.

   Filtered shots: a UV or infrared white balance set off grass or a grey card is usually not the colour of any real
   light (this file's is 0.21 off the blackbody line, where Lightroom's whole tint range is about 0.05), so a Kelvin
   figure for it would be invented. When the shot's own white balance is that far off, the slider stays +/- and a short
   note says why. */
const WBK_XYZ_RGB = [0.412453, 0.357580, 0.180423, 0.212671, 0.715160, 0.072169, 0.019334, 0.119193, 0.950227];
const WBK_MIN = 1500, WBK_MAX = 25000, WBK_DUV = 0.05;

function wbkInv3(m) {
  const [a, b, c, d, e, f, g, h, i] = m;
  const A = e * i - f * h, B = -(d * i - f * g), C = d * h - e * g;
  const det = a * A + b * B + c * C;
  if (!det || !isFinite(det)) return null;
  return [A / det, -(b * i - c * h) / det, (b * f - c * e) / det,
          B / det, (a * i - c * g) / det, -(a * f - c * d) / det,
          C / det, -(a * h - b * g) / det, (a * e - b * d) / det];
}
function wbkMulV(m, v) { return [m[0] * v[0] + m[1] * v[1] + m[2] * v[2], m[3] * v[0] + m[4] * v[1] + m[5] * v[2], m[6] * v[0] + m[7] * v[1] + m[8] * v[2]]; }

/* rgb_cam as LibRaw builds it from a table row: cam_rgb = cam_xyz . xyz_rgb, rows scaled to sum to 1, inverted. */
function wbkRgbCamFrom(camXyz) {
  const c = [];
  for (let r = 0; r < 3; r++) for (let k = 0; k < 3; k++) {
    let s = 0; for (let j = 0; j < 3; j++) s += camXyz[r * 3 + j] * WBK_XYZ_RGB[j * 3 + k];
    c.push(s);
  }
  for (let r = 0; r < 3; r++) { const s = c[r * 3] + c[r * 3 + 1] + c[r * 3 + 2]; if (!s) return null; for (let k = 0; k < 3; k++) c[r * 3 + k] /= s; }
  return wbkInv3(c);
}

/* The camera's XYZ->camera matrix for this decode, or null. Cached on the result. */
function wbkCamera(res) {
  if (!res) return null;
  if (res.__wbk !== undefined) return res.__wbk;
  res.__wbk = null;
  if (typeof WBK_TABLE === 'undefined' || !res.rgbCam || res.rgbCam.length < 12) return null;
  const rc = pp_rgbCam3x3(res.rgbCam);
  if (rc[0] === 1 && rc[1] === 0 && rc[4] === 1 && rc[8] === 1) return null;   // no calibration came with the file
  for (const row of WBK_TABLE) {
    const camXyz = row[2].map(v => v / 10000);
    const m = wbkRgbCamFrom(camXyz);
    if (!m) continue;
    let err = 0; for (let k = 0; k < 9; k++) err = Math.max(err, Math.abs(m[k] - rc[k]));
    if (err < 2e-3) {
      const xyzCam = wbkInv3(camXyz), rcInv = wbkInv3(rc);
      if (xyzCam && rcInv) res.__wbk = { xyzCam, rcInv, name: row[0] + ' ' + row[1] };
      break;
    }
  }
  return res.__wbk;
}

/* Planckian locus in CIE 1960 uv (Krystek 1985; good from 1000 K to well past 15000 K). */
function wbkPlanckUV(T) {
  return [(0.860117757 + 1.54118254e-4 * T + 1.28641212e-7 * T * T) / (1 + 8.42420235e-4 * T + 7.08145163e-7 * T * T),
          (0.317398726 + 4.22806245e-5 * T + 4.20481691e-8 * T * T) / (1 - 2.89741816e-5 * T + 1.61456053e-7 * T * T)];
}
/* Correlated colour temperature and Duv of an XYZ colour: the nearest point of the locus, searched in mireds. */
function wbkCCT(XYZ) {
  const d = XYZ[0] + 15 * XYZ[1] + 3 * XYZ[2];
  if (!(d > 0) || !(XYZ[1] > 0)) return null;
  const u = 4 * XYZ[0] / d, v = 6 * XYZ[1] / d;
  const dist = mr => { const p = wbkPlanckUV(1e6 / mr); return (p[0] - u) * (p[0] - u) + (p[1] - v) * (p[1] - v); };
  let best = 40, bd = Infinity;
  for (let mr = 30; mr <= 1100; mr += 5) { const e = dist(mr); if (e < bd) { bd = e; best = mr; } }
  let lo = Math.max(20, best - 5), hi = best + 5;   // golden-section polish
  for (let k = 0; k < 40; k++) {
    const a = lo + (hi - lo) * 0.382, b = lo + (hi - lo) * 0.618;
    if (dist(a) < dist(b)) hi = b; else lo = a;
  }
  const mr = (lo + hi) / 2, T = 1e6 / mr, p = wbkPlanckUV(T);
  return { T, duv: Math.sqrt(dist(mr)) * (v >= p[1] ? 1 : -1) };
}

/* The RAW result behind the picture on screen, if the picture on screen is a RAW. */
function wbkRes() {
  try {
    if (typeof rawEngine === 'undefined' || !rawEngine.lastResult || rawEngine.lastGen !== loadToken) return null;
    const res = rawEngine.lastResult;
    return res.__wb ? res : null;
  } catch (e) { return null; }
}

/* The light that comes out neutral for slider effect values t (temperature) and m (tint), in Kelvin with its Duv. */
function wbkLightFor(tEff, mEff) {
  const res = wbkRes(), cam = wbkCamera(res);
  if (!cam) return null;
  const t = tEff / 100, m = mEff / 100;   // the gains tempTintGains applies (its overall scale cancels here)
  let g = [Math.exp(0.28 * t + 0.12 * m), Math.exp(-0.16 * m), Math.exp(-0.28 * t + 0.12 * m)];
  try { if (typeof wbMethod !== 'undefined' && wbMethod !== 'bradford' && Array.isArray(preWB)) g = g.map((x, i) => x * (preWB[i] || 1)); } catch (e) {}
  const out = wbkMulV(cam.rcInv, g.map(x => 1 / x));           // undo the gains, then back to balanced camera values
  const camLight = out.map((x, i) => x / res.__wb[i]);         // and undo the decode's white balance
  return wbkCCT(wbkMulV(cam.xyzCam, camLight));
}

/* Kelvin applies when the shot's own white balance (slider at 0) is a real light. */
function wbkActive() {
  const b = wbkLightFor(0, 0);
  return !!(b && b.T >= WBK_MIN && b.T <= WBK_MAX && Math.abs(b.duv) <= WBK_DUV);
}
function wbkTintNow() { return wbEff($('tint') ? $('tint').value : 0); }
function wbkKelvinAt(tEff) { const l = wbkLightFor(tEff, wbkTintNow()); return l ? l.T : null; }
function wbkFmt(T) {
  if (T == null) return '';
  if (T < WBK_MIN) return '<' + WBK_MIN + ' K';
  if (T > WBK_MAX) return '>' + WBK_MAX + ' K';
  return (Math.round(T / 50) * 50) + ' K';
}
/* Slider effect value giving a Kelvin target (the readout rises with the slider, so bisection). */
function wbkEffFor(K) {
  let lo = -600, hi = 600;
  const kLo = wbkKelvinAt(lo), kHi = wbkKelvinAt(hi);
  if (kLo == null || kHi == null) return null;
  if (K <= kLo) return lo;
  if (K >= kHi) return hi;
  for (let k = 0; k < 40; k++) { const mid = (lo + hi) / 2; if (wbkKelvinAt(mid) < K) lo = mid; else hi = mid; }
  return (lo + hi) / 2;
}
/* Shows or hides the "outside the Kelvin scale" note: only for a RAW whose camera we know but whose light is off it. */
function wbkSyncNote() {
  const n = $('wbkNote'); if (!n) return;
  const res = wbkRes(), off = !!(res && wbkCamera(res) && !wbkActive());
  if (n.hidden === off) n.hidden = !off;
}
